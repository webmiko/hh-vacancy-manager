"""Абстрактный класс для работы с файлами.

Модуль содержит абстрактный класс FileSaverBase, который определяет
интерфейс для работы с различными форматами файлов для сохранения вакансий.
"""

# 1. Импорты стандартной библиотеки
from abc import ABC, abstractmethod
from typing import Any, Dict, List

# 2. Импорты сторонних библиотек
# (нет сторонних библиотек)

# 3. Импорты из проекта
# (нет локальных импортов)

# 4. Константы модуля
DEFAULT_RETURN_VALUE: List[Dict[str, Any]] = []


class FileSaverBase(ABC):
    """Абстрактный класс для работы с файлами для сохранения вакансий.

    Определяет интерфейс для добавления, получения и удаления вакансий
    из файлов различных форматов. Все классы для работы с конкретными
    форматами файлов должны наследоваться от этого класса.

    Attributes:
        _filename: Имя файла для сохранения данных (приватный атрибут)
    """

    @abstractmethod
    def add_vacancy(self, vacancy: Any) -> None:
        """
        Добавляет вакансию в файл.

        Args:
            vacancy: Объект вакансии для добавления

        Raises:
            IOError: При ошибках записи в файл
            ValueError: При неверных данных вакансии
        """
        pass

    @abstractmethod
    def get_vacancies(self, **criteria: Any) -> List[Dict[str, Any]]:
        """
        Получает вакансии из файла по критериям.

        Args:
            **criteria: Критерии фильтрации (ключевые слова, диапазон зарплат и т.д.)

        Returns:
            Список словарей с данными о вакансиях.
            Возвращает пустой список при ошибке или если вакансии не найдены.
        """
        pass

    @abstractmethod
    def delete_vacancy(self, vacancy: Any) -> None:
        """
        Удаляет вакансию из файла.

        Args:
            vacancy: Объект вакансии для удаления

        Raises:
            IOError: При ошибках чтения/записи файла
            ValueError: Если вакансия не найдена
        """
        pass
