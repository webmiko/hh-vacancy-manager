"""Абстрактный класс для работы с API вакансий.

Модуль содержит абстрактный класс APIBase, который определяет
интерфейс для работы с различными API платформ с вакансиями.
"""

# 1. Импорты стандартной библиотеки
from abc import ABC, abstractmethod
from typing import Any, Dict, List

# 2. Импорты сторонних библиотек
# (нет сторонних библиотек)

# 3. Импорты из проекта
# (нет локальных импортов)

# 4. Константы модуля
DEFAULT_RETURN_VALUE: List[Dict[str, Any]] = []


class APIBase(ABC):
    """Абстрактный класс для работы с API платформ с вакансиями.

    Определяет интерфейс для подключения к API и получения вакансий.
    Все классы для работы с конкретными API должны наследоваться от этого класса
    и реализовывать абстрактные методы.

    Attributes:
        _url: Базовый URL API (приватный атрибут)
        _headers: Заголовки для запросов (приватный атрибут)
        _params: Параметры запросов (приватный атрибут)
    """

    @abstractmethod
    def connect(self) -> None:
        """
        Подключается к API и проверяет доступность.

        Метод должен выполнять проверку подключения к API,
        например, отправлять тестовый запрос и проверять статус-код ответа.

        Raises:
            ConnectionError: Если не удалось подключиться к API
            requests.RequestException: При ошибках сетевого запроса
        """
        pass

    @abstractmethod
    def get_vacancies(self, keyword: str) -> List[Dict[str, Any]]:
        """
        Получает вакансии по ключевому слову.

        Args:
            keyword: Ключевое слово для поиска вакансий

        Returns:
            Список словарей с данными о вакансиях.
            Возвращает пустой список при ошибке.

        Raises:
            requests.RequestException: При ошибках сетевого запроса
            ValueError: При неверных параметрах запроса
        """
        pass
